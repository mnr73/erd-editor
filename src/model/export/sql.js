import { indexName } from "../indexes";
import { parseType } from "../types";
import {
    columnNames,
    defaultKind,
    fkName,
    resolveRefs,
    sqlString,
} from "./common";

/**
 * Document → SQL DDL for one dialect: generic (ANSI-ish), mysql, postgres, sqlite, mssql.
 *
 * Output order: [CREATE SCHEMA] → CREATE TABLE (with PK / UNIQUE / defaults) → CREATE INDEX →
 * foreign keys (ALTER TABLE ... ADD CONSTRAINT; inline for SQLite, which cannot add them later) →
 * comments. Things a dialect cannot express are converted and reported as warnings, never dropped
 * silently: `unsigned` outside MySQL, arrays outside PostgreSQL, ENUM outside MySQL (→ CHECK),
 * many-to-many refs (no single FK).
 */

export const SQL_DIALECTS = ["generic", "mysql", "postgres", "sqlite", "mssql"];

const QUOTE = {
    generic: (s) => `"${s.replace(/"/g, '""')}"`,
    postgres: (s) => `"${s.replace(/"/g, '""')}"`,
    sqlite: (s) => `"${s.replace(/"/g, '""')}"`,
    mysql: (s) => `\`${s.replace(/`/g, "``")}\``,
    mssql: (s) => `[${s.replace(/]/g, "]]")}]`,
};

/** `{ sql, warnings }`. */
export function toSql(doc, dialect = doc.meta.dbType || "generic") {
    const d = SQL_DIALECTS.includes(dialect) ? dialect : "generic";
    const q = QUOTE[d];
    const warnings = [];
    const warn = (code, extra = {}) => warnings.push({ code, ...extra });
    const tname = (t) => (t.schema ? `${q(t.schema)}.${q(t.name)}` : q(t.name));
    const out = [];

    out.push(
        `-- ${doc.meta.name || "diagram"}${d === "generic" ? "" : ` (${d})`}`,
    );
    if (doc.meta.note)
        for (const l of doc.meta.note.split("\n")) out.push(`-- ${l}`);
    out.push("-- generated by ERD Editor", "");

    if (d === "postgres" || d === "generic") {
        const schemas = [
            ...new Set(doc.tables.map((t) => t.schema).filter(Boolean)),
        ];
        for (const s of schemas)
            out.push(`CREATE SCHEMA IF NOT EXISTS ${q(s)};`);
        if (schemas.length) out.push("");
    }

    const checks = (t) => t.columns.map((c) => [c, parseType(c.type)]);
    const comments = []; // postgres COMMENT ON statements

    for (const t of doc.tables) {
        const pkCols = t.columns.filter((c) => c.pk);
        const lines = [];
        const sqliteRowid =
            d === "sqlite" &&
            pkCols.length === 1 &&
            pkCols[0].increment &&
            /^(int|integer|bigint|smallint|tinyint|mediumint)\b/i.test(
                pkCols[0].type,
            );

        for (const [c, p] of checks(t)) {
            let type = c.type || "text";
            const checkValues = [];
            if (p) {
                let base = p.base;
                let params = p.params;
                let unsigned = p.unsigned;
                let array = p.array;
                if (base === "enum") {
                    if (d === "mysql") {
                        type = `enum(${params.map(sqlString).join(",")})`;
                    } else {
                        const width = Math.max(
                            1,
                            ...params.map((v) => v.length),
                        );
                        type =
                            d === "mssql"
                                ? `nvarchar(${width})`
                                : `varchar(${width})`;
                        checkValues.push(...params);
                        warn("enum-as-check", {
                            table: t.name,
                            column: c.name,
                        });
                    }
                } else {
                    if (unsigned && d !== "mysql") {
                        warn("unsigned-dropped", {
                            table: t.name,
                            column: c.name,
                        });
                        unsigned = false;
                    }
                    if (array && d !== "postgres") {
                        warn("array-unsupported", {
                            table: t.name,
                            column: c.name,
                        });
                        array = false;
                        base = d === "mysql" ? "json" : "text";
                        params = [];
                    }
                    type = base;
                    if (params.some((v) => v !== null && v !== undefined)) {
                        let last = params.length - 1;
                        while (last > 0 && params[last] == null) last--;
                        type += `(${params
                            .slice(0, last + 1)
                            .map((v) => v ?? "")
                            .join(",")})`;
                    }
                    if (array) type += "[]";
                    if (unsigned) type += " unsigned";
                    // dialect spellings
                    if (d === "postgres" && base === "datetime")
                        type = type.replace(/^datetime/, "timestamp");
                    if (d === "postgres" && base === "double")
                        type = "double precision";
                    if (d === "mssql" && base === "boolean") type = "bit";
                    if (d === "mssql" && base === "timestamp")
                        type = type.replace(/^timestamp/, "datetime2");
                    if (d === "mssql" && base === "double") type = "float";
                    if (d === "mssql" && base === "json")
                        type = "nvarchar(max)";
                    if (d === "mssql" && base === "uuid")
                        type = "uniqueidentifier";
                    if (d === "mssql" && base === "blob")
                        type = "varbinary(max)";
                    if (d === "mssql" && base === "text")
                        type = "nvarchar(max)";
                    if (d === "postgres" && base === "blob") type = "bytea";
                    if (d === "postgres" && base === "tinyint")
                        type = "smallint";
                    if (d === "postgres" && base === "mediumint") type = "int";
                    if (d === "sqlite" && base === "uuid") type = "text";
                    if (d === "sqlite" && base === "json") type = "text";
                }
            }

            const parts = [q(c.name)];
            let typeSql = type;
            let identity = "";
            if (c.increment) {
                if (d === "mysql") identity = " AUTO_INCREMENT";
                else if (d === "mssql") identity = " IDENTITY(1,1)";
                else if (d === "postgres" || d === "generic")
                    identity = " GENERATED BY DEFAULT AS IDENTITY";
                else if (d === "sqlite" && sqliteRowid && c.pk) {
                    typeSql = "INTEGER";
                    identity = " PRIMARY KEY AUTOINCREMENT";
                } else if (d === "sqlite")
                    warn("autoincrement-dropped", {
                        table: t.name,
                        column: c.name,
                    });
            }
            parts.push(typeSql);
            let col = parts.join(" ");
            if (c.notNull || c.pk) col += " NOT NULL";
            col += identity;
            if (c.default) col += ` DEFAULT ${defaultSql(c.default, d)}`;
            if (c.unique && !c.pk) col += " UNIQUE";
            if (checkValues.length)
                col += ` CHECK (${q(c.name)} IN (${checkValues.map(sqlString).join(", ")}))`;
            if (c.note && d === "mysql") col += ` COMMENT ${sqlString(c.note)}`;
            lines.push(col);
        }

        if (pkCols.length && !sqliteRowid)
            lines.push(
                `PRIMARY KEY (${pkCols.map((c) => q(c.name)).join(", ")})`,
            );

        // SQLite cannot ALTER TABLE ... ADD CONSTRAINT: foreign keys go inline there
        const { refs } = resolveRefs(doc);
        if (d === "sqlite") {
            for (const r of refs.filter((x) => x.from.id === t.id))
                lines.push(fkClause(r, d, q, tname, true));
        }

        const sep = ",\n  ";
        const noteLines = [];
        if (t.note && d !== "mysql" && d !== "postgres")
            for (const l of t.note.split("\n")) noteLines.push(`-- ${l}`);
        if (d !== "mysql" && d !== "postgres")
            for (const c of t.columns)
                if (c.note)
                    noteLines.push(`-- ${c.name}: ${c.note.split("\n")[0]}`);
        out.push(...noteLines);
        const table =
            d === "mysql" && t.note ? ` COMMENT=${sqlString(t.note)}` : "";
        out.push(
            `CREATE TABLE ${tname(t)} (\n  ${lines.join(sep)}\n)${table};`,
            "",
        );

        if (d === "postgres") {
            if (t.note)
                comments.push(
                    `COMMENT ON TABLE ${tname(t)} IS ${sqlString(t.note)};`,
                );
            for (const c of t.columns)
                if (c.note)
                    comments.push(
                        `COMMENT ON COLUMN ${tname(t)}.${q(c.name)} IS ${sqlString(c.note)};`,
                    );
        }
    }

    const indexLines = [];
    for (const t of doc.tables) {
        for (const ix of t.indexes) {
            const cols = columnNames(t, ix.columns);
            if (!cols.length) continue;
            const name = indexName(t, ix).replace(/[^A-Za-z0-9_]/g, "_");
            const using =
                ix.type && d === "postgres" ? ` USING ${ix.type}` : "";
            const after =
                ix.type && d === "mysql"
                    ? ` USING ${ix.type.toUpperCase()}`
                    : "";
            indexLines.push(
                `CREATE ${ix.unique ? "UNIQUE " : ""}INDEX ${q(name)} ON ${tname(t)}${using} (${cols.map(q).join(", ")})${after};`,
            );
        }
    }
    if (indexLines.length) out.push(...indexLines, "");

    const { refs, warnings: refWarnings } = resolveRefs(doc);
    warnings.push(...refWarnings);
    if (d !== "sqlite") {
        for (const r of refs)
            out.push(
                `ALTER TABLE ${tname(r.from)} ADD ${fkClause(r, d, q, tname, false)};`,
            );
        if (refs.length) out.push("");
    }

    if (comments.length) out.push(...comments, "");
    return {
        sql:
            out
                .join("\n")
                .replace(/\n{3,}/g, "\n\n")
                .trimEnd() + "\n",
        warnings,
    };
}

function fkClause({ ref, to, from, fromCols, toCols }, d, q, tname, inline) {
    const name = fkName(from, fromCols);
    const parts = [
        inline ? "" : `CONSTRAINT ${q(name)} `,
        `FOREIGN KEY (${fromCols.map(q).join(", ")}) REFERENCES ${tname(to)} (${toCols.map(q).join(", ")})`,
    ];
    if (ref.onDelete) parts.push(` ON DELETE ${ref.onDelete.toUpperCase()}`);
    if (ref.onUpdate) parts.push(` ON UPDATE ${ref.onUpdate.toUpperCase()}`);
    return parts.join("");
}

function defaultSql(value, d) {
    const v = String(value).trim();
    switch (defaultKind(v)) {
        case "number":
            return v;
        case "keyword": {
            const k = v.toLowerCase();
            if (k === "null") return "NULL";
            if (d === "mssql" || d === "sqlite")
                return k === "true" ? "1" : "0";
            return k.toUpperCase();
        }
        case "string":
            return v;
        case "expr":
            return /^now\(\)$/i.test(v) && d !== "mysql" && d !== "postgres"
                ? "CURRENT_TIMESTAMP"
                : d === "mssql" && /^current_timestamp$/i.test(v)
                  ? "GETDATE()"
                  : v.toUpperCase().startsWith("CURRENT_")
                    ? v.toUpperCase()
                    : v;
        default:
            return sqlString(v);
    }
}
